/** Throws on a record that is not well formed; returns the record. */
export function validateRecord(rec) {
  if (rec?.kind !== 'moon-forge-mirrors' || rec.version !== 1) throw new Error('mirrors.json: kind/version');
  if (!Array.isArray(rec.gateways) || rec.gateways.length < 2) throw new Error('mirrors.json: at least two gateways');
  for (const g of rec.gateways) if (!/^[a-z0-9.-]+\.[a-z]{2,}$/.test(g)) throw new Error(`mirrors.json: bad gateway ${g}`);
  if (!Array.isArray(rec.mirrors)) throw new Error('mirrors.json: mirrors must be a list');
  const seen = new Set();
  for (const m of rec.mirrors) {
    if (!ID_RE.test(m.manifest ?? '')) throw new Error(`mirrors.json: bad manifest id ${m.manifest}`);
    if (seen.has(m.manifest)) throw new Error(`mirrors.json: manifest ${m.manifest} listed twice`);
    seen.add(m.manifest);
    if (!COMMIT_RE.test(m.commit ?? '')) throw new Error(`mirrors.json: ${m.manifest}: commit must be 40 hex`);
    if (!/^[0-9a-f]{64}$/.test(m.manifestSha256 ?? '')) throw new Error(`mirrors.json: ${m.manifest}: manifestSha256`);
    if (Number.isNaN(Date.parse(m.uploadedAt))) throw new Error(`mirrors.json: ${m.manifest}: uploadedAt`);
    if (m.bundle != null) {
      if (!ID_RE.test(m.bundle.id ?? '') || !/^[0-9a-f]{64}$/.test(m.bundle.sha256 ?? '') || !m.bundle.ref) throw new Error(`mirrors.json: ${m.manifest}: bundle needs id, sha256 and ref`);
    }
  }
  return rec;
}

/** The record with one more mirror (newest last). */
export function appendMirror(rec, entry) {
  const next = { ...rec, mirrors: [...rec.mirrors, entry] };
  return validateRecord(next);
}

