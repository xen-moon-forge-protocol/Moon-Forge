const dateOf = (m) => m.uploadedAt.slice(0, 10);

/** The `mirrors` list of public/links.json: the newest first. */
export function linksMirrors(rec) {
  return [...rec.mirrors].reverse().map((m) => ({
    manifest: m.manifest,
    date: dateOf(m),
    commit: m.commit,
    urls: mirrorUrls(m.manifest, rec.gateways),
    ...(m.bundle ? { bundle: { url: `https://${rec.gateways[0]}/${m.bundle.id}`, sha256: m.bundle.sha256, ref: m.bundle.ref } } : {}),
  }));
}

