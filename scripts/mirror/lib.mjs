/** The Markdown block (README, docs/HOW-IT-WORKS.md) between the markers; empty when no mirror exists. */
export function markdownBlock(rec) {
  if (!rec.mirrors.length) return `${MARK_START}\n${MARK_END}`;
  const rows = linksMirrors(rec).slice(0, 3).map((m) => `- ${m.date}, commit \`${m.commit.slice(0, 12)}\`: ${m.urls.map((u) => `<${u}>`).join(' or ')}${m.bundle ? ` (full git history: <${m.bundle.url}>, sha256 \`${m.bundle.sha256}\`)` : ''}`);
  return [
    MARK_START,
    '**If the site or this repository is down:** read-only copies of the site, the AI texts (`llms.txt`, `llms-full.txt`, `.well-known/agent-card.json`) and the repository files are stored on Arweave. Each is a snapshot of the commit it names, served by any Arweave gateway (two are listed); the repository files are under `source/`, and `MIRROR.json` lists every file with its sha256. Check the X1 program ID `57UE1U1t23ztg2noLp8pcpGW1B1Xw25rLH6ra9Mchea9` before signing anything.',
    '',
    ...rows,
    MARK_END,
  ].join('\n');
}

/** Replaces the marker block in a Markdown file; throws when the markers are missing. */
export function replaceBlock(text, block) {
  const re = new RegExp(`${escapeRe(MARK_START)}[\\s\\S]*?${escapeRe(MARK_END)}`);
  if (!re.test(text)) throw new Error('no mirrors marker block');
  return text.replace(re, () => block);
}
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** The agent card with one service per gateway for the newest mirror (none when no mirror exists). */
export function agentCardWithMirrors(card, rec) {
  const services = card.services.filter((s) => !/^arweave-mirror(-\d+)?$/.test(s.name));
  const newest = rec.mirrors[rec.mirrors.length - 1];
  if (newest) {
    const urls = mirrorUrls(newest.manifest, rec.gateways);
    const at = services.findIndex((s) => s.name === 'source');
    const add = urls.map((u, i) => ({ name: i ? `arweave-mirror-${i + 1}` : 'arweave-mirror', endpoint: u }));
    services.splice(at < 0 ? services.length : at + 1, 0, ...add);
  }
  return { ...card, services };
}

/** Serializes an agent card the way the repository keeps it: one service per line. */
export function serializeCard(card) {
  const lines = JSON.stringify({ ...card, services: '__S__' }, null, 2).split('\n');
  const svc = card.services.map((s, i) => `    ${JSON.stringify(s).replace(/^\{"name":/, '{ "name": ').replace(/,"endpoint":/, ', "endpoint": ').replace(/\}$/, ' }')}${i < card.services.length - 1 ? ',' : ''}`);
  return lines.map((l) => (l.includes('"__S__"') ? `  "services": [\n${svc.join('\n')}\n  ]${l.trim().endsWith(',') ? ',' : ''}` : l)).join('\n') + '\n';
}
