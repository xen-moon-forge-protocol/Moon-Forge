// The example week-so-far feed v1 (burn.mjs FEED CONTRACT): one golden world's window at one hour, with the raw part
// (what the kit and the oracle value) and every derived field the website reads (capacity, xnt floor/build, readings,
// skipped, per-chain Lnow/Lprev/capE18/spotE18 and the curve state S/hour/hourSpot), all computed by the kit's port of
// the oracle engine. It is the contract example for the oracle's hourly writer and for the site's parser.
//
//   node test/vectors/gen-week-so-far.mjs          (npm run vectors:feed) rewrites week-so-far.v1.json
//
// The file also carries one candidate burn and the kit's binding number for it, so another client can check that it
// quotes the same burn the same way.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { feedInputs, normalizeFeed, quoteBurn } from '../../burn.mjs';
import { allocateWindow, HOUR, NoXenPriceError } from '../../quote-v3.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
export const FEED_FIXTURE = path.join(here, 'week-so-far.v1.json');
const s = (x) => (typeof x === 'bigint' ? x.toString() : x);
const min = (a, b) => (a < b ? a : b);

/** The canonical feed: `feed` (kit form, raw) completed with every derived field, from the window and `prev`. */
export function supersetFeed(feed, prev) {
  let nf = normalizeFeed(feed).feed;
  // a chain with a burn that has no XEN price is listed skipped, as the build skips it (oracle feed-v3.ts weekSoFarStateV3)
  let r;
  for (const seen = new Set(); ;) {
    try {
      r = allocateWindow(prev ?? null, feedInputs(nf), { applyLimit: false });
      break;
    } catch (e) {
      if (!(e instanceof NoXenPriceError) || seen.has(e.chainId)) throw e;
      seen.add(e.chainId);
      nf = { ...nf, chains: nf.chains.map((c) => (c.chainId === e.chainId ? { chainId: c.chainId, name: c.name, portal: c.portal, status: 'skipped' } : c)) };
    }
  }
  const chains = nf.chains.map((c) => {
    if (c.status === 'skipped') return { ...c };
    const ch = r.chains.get(c.chainId);
    const mine = r.burns.filter((b) => b.chainId === c.chainId);
    let curveState;
    if (!mine.length) curveState = { S: s(ch.curveStart.S), hour: ch.curveStart.hour, hourSpot: '0' };
    else {
      const last = Math.max(...mine.map((b) => b.hour));
      const V = mine.filter((b) => b.hour === last).reduce((a, b) => a + b.spotMicro, 0n);
      curveState = { S: s(ch.curveAfter.S - V), hour: ch.curveAfter.hour, hourSpot: s(V) };
    }
    return {
      ...c, Lnow: String(c.liquidityNowMicro), Lprev: ch.Lprev === null ? null : s(ch.Lprev), capE18: s(ch.priceCapE18),
      spotE18: s(min(BigInt(c.market.spotE18), ch.priceCapE18)), ...curveState,
    };
  });
  const pair = (m, l, src) => (src === 'fallback' ? null : [m, l]);
  const valued = chains.filter((c) => c.status !== 'skipped' && c.current);
  const hour = nf.xnt.current?.hour ?? valued[0]?.current.hour ?? null;
  return {
    ...nf,
    prevDataHash: nf.prevEpoch?.dataHash ?? null,
    // D-12 / D-18: the senior a new burn of the window claims after (the backlog and the operator burns rank after it)
    capacity: { cash: s(r.C), senior: s(r.capacity.seniorAhead) },
    xnt: { ...nf.xnt, buildE18: s(r.xBuild), floorE18: s(r.xFloor) },
    readings: {
      hour,
      xen: Object.fromEntries(valued.map((c) => [String(c.chainId), pair(c.current.medianE18, c.current.lastCloseE18, c.current.priceSource)])),
      xnt: nf.xnt.current ? pair(nf.xnt.current.medianE18, nf.xnt.current.lastCloseE18, nf.xnt.current.source) : null,
    },
    skipped: chains.filter((c) => c.status === 'skipped').map((c) => c.chainId),
    chains,
  };
}

/** Builds the fixture from the burn tests' scenario inputs (passed in, so the file is reproducible from the vectors). */
export function buildFixture({ feed, prev, prevRef, candidate }) {
  const full = supersetFeed(feed, prev);
  const q = quoteBurn({ feed: full, prev, now: full.asOf, allowBelowMarket: true, ...candidate });
  if (!q.ok) throw new Error(`the fixture's candidate is refused: ${JSON.stringify(q.refusals)}`);
  return {
    about: 'Example week-so-far feed v1 (agents/kit/burn.mjs FEED CONTRACT), generated by agents/kit/test/vectors/gen-week-so-far.mjs from the golden quote vectors. Not real burns.',
    prevRef,
    feed: full,
    candidate: { ...candidate, amountWei: String(candidate.amountWei), now: full.asOf },
    expected: { bindingNow: s(q.bindingNow), entitlement: s(q.entitlement), day: q.tranche.day, remainingToday: s(q.tranche.remainingToday), hour: Math.floor(full.asOf / HOUR) },
  };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { fixtureInputs } = await import('../unit/helpers-v3.mjs');
  const fx = buildFixture(await fixtureInputs());
  fs.writeFileSync(FEED_FIXTURE, JSON.stringify(fx, null, 1) + '\n');
  console.log(`wrote ${path.relative(process.cwd(), FEED_FIXTURE)}: epoch ${fx.feed.epoch}, ${fx.feed.chains.length} chains, ${fx.feed.chains.reduce((n, c) => n + (c.burns?.length ?? 0), 0)} burns`);
}
